/**
 * §4.9 corporate records: filled from database data, rendered to PDF, signed
 * by the owner, vaulted. These are the entity's own internal formalities —
 * never IRS/NYS forms (guardrail 4). Each carries a review note: the app is
 * not a lawyer or tax adviser.
 */
